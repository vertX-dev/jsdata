/// The full version/tag precedence chain, end to end: pin > CLI > config, with
/// the two halves resolving independently.
#[test]
fn version_and_tag_precedence() {
    use jsdata::version::VersionSpec;

    let d = scratch("vtags");
    fs::create_dir_all(d.join("src")).unwrap();
    // TAGGED has one block per tag; UNTAGGED content is always kept.
    let src = "export const A = {\n  base: 0,\n  //version 2.1 [beta]*\n  beta: 1,\n  //version 2.1 [beta]*\n  //version 2.1 [ui]*\n  ui: 2,\n  //version 2.1 [ui]*\n  //version 2.9 *\n  future: 3,\n  //version 2.9 *\n};\n";
    fs::write(d.join("src/a.js"), src).unwrap();
    let cfg = d.join("jsdata.cfg");
    let out = d.join("_wikiData.js");
    let read = || fs::read_to_string(&out).unwrap();

    // 1. Config defaults apply.
    fs::write(
        &cfg,
        "version = 2.5\nversionTags = [beta]\nvar A = src/a.js -> const A\n",
    )
    .unwrap();
    assert!(jsdata::build(&cfg, true, None).errors.is_empty());
    let js = read();
    assert!(js.contains("base: 0") && js.contains("beta: 1"), "{js}");
    assert!(!js.contains("ui: 2"), "tag filter ignored: {js}");
    assert!(!js.contains("future: 3"), "version bound ignored: {js}");

    // 2. CLI overrides the config, per half. --tag ui alone must not disturb
    //    the config's version bound.
    let opts = jsdata::Options {
        version: VersionSpec {
            spec: None,
            tags: Some(vec!["ui".into()]),
        },
    };
    assert!(jsdata::build_with(&cfg, true, &opts).errors.is_empty());
    let js = read();
    assert!(js.contains("ui: 2") && !js.contains("beta: 1"), "{js}");
    assert!(!js.contains("future: 3"), "config version lost: {js}");

    // 3. A pin beats both — and a pin naming no tags still inherits them.
    fs::write(
        &cfg,
        "version = 2.5\nversionTags = [beta]\nvar A = src/a.js -> const A --- 2.9\n",
    )
    .unwrap();
    assert!(jsdata::build(&cfg, true, None).errors.is_empty());
    let js = read();
    assert!(js.contains("future: 3"), "pin version not applied: {js}");
    assert!(js.contains("beta: 1"), "pin dropped inherited tags: {js}");
    assert!(!js.contains("ui: 2"), "{js}");

    // 4. `[]` on a pin means "no tags active here", overriding the inherited
    //    `versionTags` — tags are opt-in, so every tagged block is skipped.
    fs::write(
        &cfg,
        "version = 2.5\nversionTags = [beta]\nvar A = src/a.js -> const A --- 2.5 []\n",
    )
    .unwrap();
    assert!(jsdata::build(&cfg, true, None).errors.is_empty());
    let js = read();
    assert!(js.contains("base: 0"), "{js}");
    assert!(!js.contains("beta: 1") && !js.contains("ui: 2"), "{js}");

    // 5. `[*]` is how you ask for every tag.
    fs::write(
        &cfg,
        "version = 2.5\nversionTags = [beta]\nvar A = src/a.js -> const A --- 2.5 [*]\n",
    )
    .unwrap();
    assert!(jsdata::build(&cfg, true, None).errors.is_empty());
    let js = read();
    assert!(js.contains("beta: 1") && js.contains("ui: 2"), "{js}");
    assert!(!js.contains("future: 3"), "pin version ignored: {js}");

    let _ = fs::remove_dir_all(&d);
}

/// Duplicate declarations of one `const`, each behind its own version block:
/// the newest **valid** one must win at every version.
#[test]
fn duplicate_declarations_resolve_by_version() {
    let d = scratch("dupdecl");
    fs::create_dir_all(d.join("src")).unwrap();
    fs::write(
        d.join("src/c.js"),
        concat!(
            "//version 1.0 1.5 *\nexport const C = { a: 1 };\n//version 1.0 1.5 *\n",
            "//version 1.5 2.0 *\nexport const C = { a: 1, b: 2 };\n//version 1.5 2.0 *\n",
            "//version 2.0 *\nexport const C = { a: 1, b: 2, c: 3 };\n//version 2.0 *\n",
        ),
    )
    .unwrap();
    let cfg = d.join("jsdata.cfg");
    fs::write(&cfg, "var C = src/c.js -> const C\n").unwrap();
    let out = d.join("_wikiData.js");

    for (spec, expect) in [
        ("1.2", "{ a: 1 }"),
        ("1.7", "{ a: 1, b: 2 }"),
        ("2.5", "{ a: 1, b: 2, c: 3 }"),
    ] {
        let o = jsdata::build(&cfg, true, Some(spec));
        assert!(o.errors.is_empty(), "{spec}: {:?}", o.errors);
        let js = fs::read_to_string(&out).unwrap();
        assert!(js.contains(expect), "at {spec} expected {expect}, got:\n{js}");
    }

    // No version at all: everything is valid, so the newest still wins — an
    // unset version means "latest", not "whichever was written first".
    let o = jsdata::build(&cfg, true, None);
    assert!(o.errors.is_empty(), "{:?}", o.errors);
    let js = fs::read_to_string(&out).unwrap();
    assert!(js.contains("{ a: 1, b: 2, c: 3 }"), "unfiltered:\n{js}");

    // Below every block nothing is valid — skipped with a warning, not fatal.
    let o = jsdata::build(&cfg, true, Some("0.9"));
    assert!(o.errors.is_empty(), "should not fail: {:?}", o.errors);
    assert!(
        o.warnings.iter().any(|w| w.contains("C") && w.contains("skipped")),
        "{:?}",
        o.warnings
    );
    let js = fs::read_to_string(&out).unwrap();
    assert!(!js.contains("export const C"), "skipped entry emitted:
{js}");

    let _ = fs::remove_dir_all(&d);
}

/// Nested markers inside the chosen declaration must still be resolved — the
/// picker selects *which* declaration, the filter cleans up *inside* it.
#[test]
fn the_chosen_declaration_is_still_filtered_inside() {
    let d = scratch("dupnested");
    fs::create_dir_all(d.join("src")).unwrap();
    fs::write(
        d.join("src/c.js"),
        concat!(
            "//version 1.0 2.0 *\nexport const C = { old: true };\n//version 1.0 2.0 *\n",
            "//version 2.0 *\n",
            "export const C = {\n  a: 1,\n  //version 2.5 *\n  b: 2,\n  //version 2.5 *\n};\n",
            "//version 2.0 *\n",
        ),
    )
    .unwrap();
    let cfg = d.join("jsdata.cfg");
    fs::write(&cfg, "var C = src/c.js -> const C\n").unwrap();
    let out = d.join("_wikiData.js");

    jsdata::build(&cfg, true, Some("2.2"));
    let js = fs::read_to_string(&out).unwrap();
    assert!(js.contains("a: 1") && !js.contains("old"), "{js}");
    assert!(!js.contains("b: 2"), "nested 2.5 block survived at 2.2:\n{js}");

    jsdata::build(&cfg, true, Some("2.5"));
    let js = fs::read_to_string(&out).unwrap();
    assert!(js.contains("b: 2"), "nested block missing at 2.5:\n{js}");

    let _ = fs::remove_dir_all(&d);
}

/// A declaration absent at the requested version is skipped with a warning, not
/// an error — one missing entry must not fail a whole build.
#[test]
fn absent_at_version_is_skipped_not_fatal() {
    let d = scratch("skipver");
    fs::create_dir_all(d.join("src")).unwrap();
    fs::write(
        d.join("src/a.js"),
        "export const ALWAYS = { a: 1 };\n//version 2.4 *\nexport const LATER = { b: 2 };\n//version 2.4 *\n",
    )
    .unwrap();
    let cfg = d.join("jsdata.cfg");
    fs::write(
        &cfg,
        "var ALWAYS = src/a.js -> const ALWAYS\nvar LATER = src/a.js -> const LATER\nlet COUNT = Object.keys(LATER).length\n",
    )
    .unwrap();

    let o = jsdata::build(&cfg, true, Some("2.0"));
    assert!(o.errors.is_empty(), "should not fail: {:?}", o.errors);
    assert_eq!(o.wrote, Some(true));
    assert!(
        o.warnings.iter().any(|w| w.contains("LATER") && w.contains("skipped")),
        "{:?}",
        o.warnings
    );
    // A `let` naming a skipped entry goes too — otherwise the module throws.
    assert!(
        o.warnings.iter().any(|w| w.contains("COUNT") && w.contains("references skipped")),
        "{:?}",
        o.warnings
    );

    // Skipped entries are silent in the output — no `undefined` placeholder.
    let js = fs::read_to_string(d.join("_wikiData.js")).unwrap();
    assert!(js.contains("ALWAYS"), "{js}");
    assert!(!js.contains("LATER"), "{js}");
    assert!(!js.contains("COUNT"), "{js}");
    assert!(!js.contains("undefined"), "{js}");

    // At 2.5 everything is back.
    let o = jsdata::build(&cfg, true, Some("2.5"));
    assert!(o.errors.is_empty(), "{:?}", o.errors);
    let js = fs::read_to_string(d.join("_wikiData.js")).unwrap();
    assert!(js.contains("LATER") && js.contains("COUNT"), "{js}");

    let _ = fs::remove_dir_all(&d);
}

/// A name that exists at *no* version is a config typo, and stays fatal.
#[test]
fn a_name_declared_nowhere_is_still_an_error() {
    let d = scratch("typo");
    fs::create_dir_all(d.join("src")).unwrap();
    fs::write(d.join("src/a.js"), "export const REAL = 1;\n").unwrap();
    let cfg = d.join("jsdata.cfg");
    fs::write(&cfg, "var X = src/a.js -> const NOSUCHTHING\n").unwrap();

    let o = jsdata::build(&cfg, true, Some("2.0"));
    assert_eq!(o.errors.len(), 1, "{:?}", o.errors);
    assert!(o.errors[0].contains("at any version"), "{:?}", o.errors);
    assert_eq!(o.wrote, None, "errors still block the write");

    let _ = fs::remove_dir_all(&d);
}

/// Markers *inside* one declaration make versions too — a list that grows an
/// entry shouldn't have to duplicate the whole literal.
#[test]
fn in_block_markers_version_a_single_declaration() {
    let d = scratch("inblock");
    fs::create_dir_all(d.join("src")).unwrap();
    fs::write(
        d.join("src/a.js"),
        concat!(
            "export const LIST = [\n",
            "  { id: \"a\" },\n",
            "  //version 2.0 *\n",
            "  { id: \"b\" },\n",
            "  //version 2.0 *\n",
            "  //version 2.5 *\n",
            "  { id: \"c\" },\n",
            "  //version 2.5 *\n",
            "];\n",
        ),
    )
    .unwrap();
    let cfg = d.join("jsdata.cfg");
    fs::write(&cfg, "var LIST = src/a.js -> const LIST\n").unwrap();
    let out = d.join("_wikiData.js");

    for (spec, items) in [("1.0", 1), ("2.0", 2), ("2.5", 3)] {
        jsdata::build(&cfg, true, Some(spec));
        let js = fs::read_to_string(&out).unwrap();
        let got = js.matches("id:").count();
        assert_eq!(got, items, "at {spec} expected {items} items:\n{js}");
    }

    // …and the report lists each version, marking the one in force.
    let opts = jsdata::Options {
        version: jsdata::version::VersionSpec::from_spec("2.0"),
    };
    let report = jsdata::structure::report(&cfg, &opts, false).unwrap();
    assert!(report.contains("3 versions"), "{report}");
    assert!(report.contains("base"), "{report}");
    assert!(
        report.lines().any(|l| l.contains("-> 2.0")),
        "selection not marked:\n{report}"
    );

    let _ = fs::remove_dir_all(&d);
}
