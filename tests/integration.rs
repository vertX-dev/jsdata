use std::fs;
use std::path::PathBuf;

fn scratch(name: &str) -> PathBuf {
    let d = std::env::temp_dir().join(format!("jsdata-it-{}-{name}", std::process::id()));
    let _ = fs::remove_dir_all(&d);
    fs::create_dir_all(&d).unwrap();
    d
}

#[test]
fn end_to_end_build() {
    let d = scratch("e2e");
    fs::create_dir_all(d.join("src/BP/scripts")).unwrap();
    fs::write(
        d.join("src/BP/scripts/main.js"),
        "import x from 'y';\nexport const PASSIVES = {\n  regen: { cost: 1 }, // };\n  haste: { cost: `${2}` },\n};\nconst other = 1;\n",
    )
    .unwrap();
    fs::write(
        d.join("jsdata.cfg"),
        "# demo\nout src/wiki/_wikiData.js\nvar PASSIVES = src/BP/scripts/main.js -> const PASSIVES\nlet PASSIVE_COUNT = Object.keys(PASSIVES).length\n",
    )
    .unwrap();

    let o = jsdata::build(&d.join("jsdata.cfg"), true, None);
    assert!(o.errors.is_empty(), "{:?}", o.errors);
    assert!(o.warnings.is_empty(), "{:?}", o.warnings);
    assert_eq!(o.wrote, Some(true));

    let out = fs::read_to_string(d.join("src/wiki/_wikiData.js")).unwrap();
    assert!(out.contains("export const PASSIVES = {\n  regen: { cost: 1 }, // };\n  haste: { cost: `${2}` },\n};"), "{out}");
    assert!(out.contains("export const PASSIVE_COUNT = Object.keys(PASSIVES).length;"));
    let p = out.find("PASSIVES =").unwrap();
    let c = out.find("PASSIVE_COUNT =").unwrap();
    assert!(p < c, "config order preserved");

    // rebuild: only the timestamp would differ -> no write
    let o2 = jsdata::build(&d.join("jsdata.cfg"), true, None);
    assert_eq!(o2.wrote, Some(false));

    // source change -> rewrite
    fs::write(
        d.join("src/BP/scripts/main.js"),
        "export const PASSIVES = { regen: { cost: 2 } };\n",
    )
    .unwrap();
    let o3 = jsdata::build(&d.join("jsdata.cfg"), true, None);
    assert_eq!(o3.wrote, Some(true));
    let out3 = fs::read_to_string(d.join("src/wiki/_wikiData.js")).unwrap();
    assert!(out3.contains("cost: 2"));
}

